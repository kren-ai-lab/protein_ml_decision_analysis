def compute_label_summary(
    standardized_df: pd.DataFrame,
    input_data: Path,
    label_col: str,
    id_col: str = "id",
    sequence_col: str = "sequence",
) -> pd.DataFrame:
    if not input_data.exists():
        raise FileNotFoundError(f"Original input data not found: {input_data}")

    original = pd.read_csv(input_data)
    if label_col not in original.columns:
        raise ValueError(
            f"Label column '{label_col}' not found in original input data. "
            f"Available columns: {original.columns.tolist()}"
        )

    before_counts = original[label_col].value_counts(dropna=False).rename("n_before_label")
    n_before_total = int(original.shape[0])

    rows = []

    for _, row in standardized_df.iterrows():
        reduced_path_raw = str(row.get("reduced_dataset", "")).strip()
        if not reduced_path_raw:
            print(
                f"[WARNING] Missing reduced dataset path for "
                f"{row['dataset_reduction_label']} {row['parameter_value']}. Skipping label analysis."
            )
            continue

        reduced_path = Path(reduced_path_raw)
        if not reduced_path.exists():
            print(f"[WARNING] Reduced dataset not found: {reduced_path}. Skipping.")
            continue

        reduced = pd.read_csv(reduced_path)
        if label_col not in reduced.columns:
            sibling = reduced_path.parent / "data_nr_labeled.csv"
            if sibling.exists():
                reduced = pd.read_csv(sibling)
                reduced_path = sibling

        if label_col not in reduced.columns:
            # Fallback: recover labels from the original dataset using id or sequence.
            join_col = None
            if id_col in reduced.columns and id_col in original.columns:
                join_col = id_col
            elif sequence_col in reduced.columns and sequence_col in original.columns:
                join_col = sequence_col

            if join_col is not None:
                label_lookup = original[[join_col, label_col]].drop_duplicates(subset=[join_col])
                reduced = reduced.merge(label_lookup, on=join_col, how="left")

        if label_col not in reduced.columns:
            print(
                f"[WARNING] Label column '{label_col}' not found in {reduced_path}, "
                "and labels could not be recovered from the original dataset. "
                "Skipping this threshold."
            )
            continue

        after_counts = reduced[label_col].value_counts(dropna=False).rename("n_after_label")
        n_after_total = int(reduced.shape[0])

        labels = sorted(set(before_counts.index.tolist()) | set(after_counts.index.tolist()), key=str)
        for label_value in labels:
            n_before_label = int(before_counts.get(label_value, 0))
            n_after_label = int(after_counts.get(label_value, 0))
            retained_label_percent = (
                n_after_label / n_before_label * 100.0 if n_before_label > 0 else pd.NA
            )
            rows.append({
                "dataset_reduction_label": row["dataset_reduction_label"],
                "reduction_kind": row["reduction_kind"],
                "parameter_type": row["parameter_type"],
                "parameter_value": row["parameter_value"],
                "label": label_value,
                "n_before_total": n_before_total,
                "n_after_total": n_after_total,
                "n_before_label": n_before_label,
                "n_after_label": n_after_label,
                "retained_label_percent": retained_label_percent,
                "before_label_percent_of_total": n_before_label / n_before_total * 100.0,
                "after_label_percent_of_total": (
                    n_after_label / n_after_total * 100.0 if n_after_total > 0 else pd.NA
                ),
                "reduced_dataset": str(reduced_path),
            })

    if not rows:
        raise RuntimeError(
            "No label-aware rows were generated. Check that reduced datasets exist and contain the label column."
        )

    out = pd.DataFrame(rows)
    return out.sort_values(
        ["dataset_reduction_label", "label", "parameter_value"]
    ).reset_index(drop=True)


def plot_label_retention(df: pd.DataFrame, output_path: Path, dpi: int) -> None:
    panel_labels = list(df["dataset_reduction_label"].drop_duplicates())
    n_panels = len(panel_labels)
    ncols = min(3, max(1, n_panels))
    nrows = math.ceil(n_panels / ncols)

    fig, axes = plt.subplots(
        nrows=nrows,
        ncols=ncols,
        figsize=(4.4 * ncols, 3.4 * nrows),
        squeeze=False,
    )
    axes_flat = axes.flatten()

    for ax, panel_label in zip(axes_flat, panel_labels):
        sub = df[df["dataset_reduction_label"] == panel_label].copy()
        sub = sub.sort_values("parameter_value")

        for label_value, label_df in sub.groupby("label", dropna=False):
            label_df = label_df.sort_values("parameter_value")
            x = list(range(len(label_df)))
            ax.plot(
                x,
                label_df["retained_label_percent"],
                marker="o",
                linewidth=1.7,
                label=str(label_value),
            )

        first_label = sub["label"].iloc[0]
        ref = sub[sub["label"] == first_label].sort_values("parameter_value")
        xticklabels = [format_parameter(v) for v in ref["parameter_value"]]
        parameter_type = str(sub["parameter_type"].iloc[0])
        xlabel = "Percentile" if parameter_type == "percentile" else parameter_type

        ax.set_ylim(0, 105)
        ax.set_title(panel_label)
        ax.set_xticks(list(range(len(xticklabels))))
        ax.set_xticklabels(xticklabels, rotation=45, ha="right")
        ax.set_xlabel(xlabel)
        ax.set_ylabel("Retained per label (%)")
        style_axis(ax)
        ax.legend(title="Label", fontsize=8, title_fontsize=8, frameon=False)

    for ax in axes_flat[n_panels:]:
        ax.axis("off")

    fig.tight_layout()
    fig.savefig(output_path, dpi=dpi, bbox_inches="tight")
    plt.close(fig)


# ---------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------


def main() -> None:
    args = parse_args()

    output_dir = Path(args.output_dir).expanduser().resolve()
    tables_dir, figures_dir = mkdir_outputs(output_dir)

    standardized_parts = []
    for spec in args.reduction_summary:
        label, kind, summary_path = parse_summary_spec(spec)
        print(f"[INFO] Reading {kind}: {summary_path}")
        standardized_parts.append(standardize_summary(label, kind, summary_path))

    standardized = pd.concat(standardized_parts, ignore_index=True)
    standardized.insert(0, "dataset_name", args.dataset_name)

    standardized_path = tables_dir / "reduction_summary_standardized.csv"
    standardized.to_csv(standardized_path, index=False)
    print(f"[INFO] Saved standardized summary: {standardized_path}")

    if args.general:
        general_fig = figures_dir / f"reduction_retained_removed_percent.{args.fig_format}"
        plot_general_panel(standardized, general_fig, args.dpi)
        print(f"[INFO] Saved general figure: {general_fig}")

    if args.by_label:
        label_summary = compute_label_summary(
            standardized_df=standardized,
            input_data=Path(args.input_data).expanduser().resolve(),
            label_col=args.label_col,
            id_col=args.id_col,
            sequence_col=args.sequence_col,
        )
        label_summary.insert(0, "dataset_name", args.dataset_name)

        label_summary_path = tables_dir / "reduction_summary_by_label.csv"
        label_summary.to_csv(label_summary_path, index=False)
        print(f"[INFO] Saved label summary: {label_summary_path}")

        label_fig = figures_dir / f"reduction_retained_by_label.{args.fig_format}"
        plot_label_retention(label_summary, label_fig, args.dpi)
        print(f"[INFO] Saved label figure: {label_fig}")

    done = output_dir / "analysis.done"
    done.write_text("done\n", encoding="utf-8")
    print(f"[INFO] Done marker: {done}")


if __name__ == "__main__":
    main()
