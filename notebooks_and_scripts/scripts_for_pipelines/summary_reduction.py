#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
Summarize data-reduction outputs generated by the unified Snakemake workflow.

The script creates two complementary analyses:

1. General reduction analysis
   - Standardizes reduction_summary.csv files from embedding-distance,
     one-hot descriptor, and homology reductions.
   - Reports retained/removed percentages for each reduction threshold.
   - Generates a panel figure with retained vs removed percentages.

2. Label-aware reduction analysis
   - Reads each reduced dataset listed in the summary files.
   - Counts how many sequences from each label are retained.
   - Computes retained percentages per label relative to the original dataset.
   - Generates a panel figure showing label-specific retention.

The script is intentionally tolerant to slightly different summary schemas. It tries
common column names and searches for sibling files such as data_nr_labeled.csv when
needed.
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path
from typing import Iterable

import matplotlib
matplotlib.use("Agg")

import matplotlib.pyplot as plt
import pandas as pd


COLOR_RETAINED = "#83c5be"
COLOR_REMOVED = "#e9a37f"


# ---------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate general and label-aware summaries for reduction outputs."
    )

    parser.add_argument(
        "--reduction-summary",
        action="append",
        required=True,
        help=(
            "Reduction summary specification in the form: "
            "<label>::<kind>::<path>. Can be repeated. "
            "Example: ESM2-8M::embedding_distance::/path/reduction_summary.csv"
        ),
    )
    parser.add_argument("--input-data", required=True, help="Original unreduced dataset CSV.")
    parser.add_argument("--dataset-name", required=True, help="Dataset name.")
    parser.add_argument("--label-col", default="label", help="Label column name.")
    parser.add_argument("--id-col", default="id", help="Sequence/sample identifier column name.")
    parser.add_argument("--sequence-col", default="sequence", help="Sequence column name.")
    parser.add_argument("--output-dir", required=True, help="Output directory for tables and figures.")
    parser.add_argument("--fig-format", default="png", choices=["png", "pdf", "svg"])
    parser.add_argument("--dpi", type=int, default=300)
    parser.add_argument("--general", action="store_true", help="Run general retained/removed analysis.")
    parser.add_argument("--by-label", action="store_true", help="Run label-aware retained analysis.")

    return parser.parse_args()


# ---------------------------------------------------------------------
# Utilities
# ---------------------------------------------------------------------


def parse_summary_spec(spec: str) -> tuple[str, str, Path]:
    parts = spec.split("::", 2)
    if len(parts) != 3:
        raise ValueError(
            "Invalid --reduction-summary format. Expected: <label>::<kind>::<path>. "
            f"Received: {spec}"
        )
    label, kind, path = parts
    return label.strip(), kind.strip(), Path(path).expanduser().resolve()


def first_existing_column(df: pd.DataFrame, candidates: Iterable[str]) -> str | None:
    for col in candidates:
        if col in df.columns:
            return col
    return None


def as_float_series(series: pd.Series) -> pd.Series:
    return pd.to_numeric(series, errors="coerce").astype(float)


def format_parameter(value: float | str) -> str:
    try:
        value_f = float(value)
    except Exception:
        return str(value)

    if value_f.is_integer():
        return str(int(value_f))
    return f"{value_f:g}"


def style_axis(ax) -> None:
    ax.grid(axis="y", alpha=0.25)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.tick_params(axis="both", labelsize=9)


def mkdir_outputs(output_dir: Path) -> tuple[Path, Path]:
    tables_dir = output_dir / "tables"
    figures_dir = output_dir / "figures"
    tables_dir.mkdir(parents=True, exist_ok=True)
    figures_dir.mkdir(parents=True, exist_ok=True)
    return tables_dir, figures_dir


# ---------------------------------------------------------------------
# Summary standardization
# ---------------------------------------------------------------------


def infer_parameter_columns(df: pd.DataFrame, kind: str) -> tuple[str, str]:
    if "percentile" in df.columns:
        return "percentile", "percentile"
    if "min_seq_id" in df.columns:
        return "min_seq_id", "min_seq_id"
    if "threshold" in df.columns:
        parameter_type = "min_seq_id" if kind == "homology" else "threshold"
        return parameter_type, "threshold"
    if "parameter_value" in df.columns:
        return df.get("parameter_type", pd.Series(["parameter"])).iloc[0], "parameter_value"

    raise ValueError(
        "Could not infer a parameter column. Expected one of: "
        "percentile, min_seq_id, threshold, parameter_value. "
        f"Available columns: {df.columns.tolist()}"
    )


def infer_count_columns(df: pd.DataFrame) -> tuple[str | None, str | None]:
    n_input_col = first_existing_column(
        df,
        ["n_input", "n_in", "n_total", "input_n", "total_input", "n_before"],
    )
    n_reduced_col = first_existing_column(
        df,
        ["n_reduced", "n_out", "n_kept", "kept_n", "n_after", "n_retained"],
    )
    return n_input_col, n_reduced_col


def infer_retained_fraction(df: pd.DataFrame) -> pd.Series:
    fraction_col = first_existing_column(
        df,
        ["kept_fraction", "retained_fraction", "fraction_kept", "kept_frac"],
    )
    if fraction_col is not None:
        values = as_float_series(df[fraction_col])
        # If values look like percentages, convert to fractions.
        if values.dropna().max() > 1.5:
            values = values / 100.0
        return values

    retained_percent_col = first_existing_column(
        df,
        ["retained_percent", "kept_percent", "percent_retained"],
    )
    if retained_percent_col is not None:
        return as_float_series(df[retained_percent_col]) / 100.0

    n_input_col, n_reduced_col = infer_count_columns(df)
    if n_input_col is not None and n_reduced_col is not None:
        n_input = as_float_series(df[n_input_col])
        n_reduced = as_float_series(df[n_reduced_col])
        return n_reduced / n_input.replace(0, pd.NA)

    raise ValueError(
        "Could not infer retained fraction. Expected kept_fraction, retained_percent, "
        "or n_input/n_reduced-like columns. "
        f"Available columns: {df.columns.tolist()}"
    )


def _deduplicate_paths(paths: list[Path]) -> list[Path]:
    seen = set()
    out = []
    for path in paths:
        key = str(path)
        if key in seen:
            continue
        seen.add(key)
        out.append(path)
    return out


def _parameter_folder_candidates(value: float | str, kind: str, parameter_type: str) -> list[str]:
    """
    Build folder-name candidates from a reduction parameter.

    Examples
    --------
    30.0 -> p30_0, p30
    99.5 -> p99_5
    0.7  -> threshold_0.7
    """
    value_raw = str(value).strip()

    try:
        value_f = float(value)
    except Exception:
        value_f = None

    candidates: list[str] = []

    if kind == "homology" or parameter_type in {"min_seq_id", "threshold"}:
        if value_f is not None:
            candidates.extend([
                f"threshold_{value_f:g}",
                f"threshold_{value_f}",
            ])
        candidates.append(f"threshold_{value_raw}")
        return list(dict.fromkeys(candidates))

    # Distance-based reductions use folders such as p30_0, p99_5, p99_9.
    if value_f is not None:
        candidates.extend([
            "p" + str(float(value_f)).replace(".", "_"),  # 30.0 -> p30_0
            "p" + f"{value_f:g}".replace(".", "_"),       # 30.0 -> p30
        ])

    candidates.append("p" + value_raw.replace(".", "_"))
    return list(dict.fromkeys(candidates))


def _existing_reduced_file(folder: Path, kind: str) -> Path | None:
    """
    Return the preferred reduced dataset file inside a threshold folder.
    """
    if kind == "homology":
        names = [
            "data_nr_labeled.csv",
            "data_nr_mmseqs2_labeled.csv",
            "data_nr_mmseqs2.csv",
            "data_nr.csv",
        ]
    else:
        names = [
            "data_nr_labeled.csv",
            "data_nr.csv",
        ]

    for name in names:
        path = folder / name
        if path.exists():
            return path.resolve()

    return None


def infer_reduced_dataset_path(
    row: pd.Series,
    summary_path: Path,
    kind: str,
    parameter_type: str,
    parameter_value: float | str,
) -> Path | None:
    """
    Infer the path to the reduced dataset for one row of a reduction summary.

    Priority:
    1. Use explicit path columns if present in the summary CSV.
    2. Resolve relative paths with respect to the summary CSV parent directory.
    3. Infer sibling threshold folders from the parameter value:
       - p30_0/data_nr_labeled.csv for distance/descriptor reductions.
       - threshold_0.7/data_nr_mmseqs2.csv for homology reductions.
    """
    path_cols = [
        "reduced_dataset_labeled",
        "data_nr_labeled",
        "labeled_dataset",
        "reduced_labeled_dataset",
        "reduced_dataset",
        "data_nr",
        "output_data",
        "output_csv",
    ]

    summary_parent = summary_path.parent

    for col in path_cols:
        if col not in row.index:
            continue
        value = row[col]
        if pd.isna(value) or str(value).strip() == "":
            continue

        raw_path = Path(str(value)).expanduser()

        path_candidates = []
        if raw_path.is_absolute():
            path_candidates.append(raw_path)
        else:
            path_candidates.extend([
                summary_parent / raw_path,
                Path.cwd() / raw_path,
                raw_path,
            ])

        for path in _deduplicate_paths(path_candidates):
            if path.exists():
                sibling = path.parent / "data_nr_labeled.csv"
                if sibling.exists():
                    return sibling.resolve()
                return path.resolve()

            sibling = path.parent / "data_nr_labeled.csv"
            if sibling.exists():
                return sibling.resolve()

    # Fallback: infer from the folder structure generated by the reduction workflow.
    for folder_name in _parameter_folder_candidates(parameter_value, kind, parameter_type):
        folder = summary_parent / folder_name
        found = _existing_reduced_file(folder, kind)
        if found is not None:
            return found

    return None


def standardize_summary(label: str, kind: str, path: Path) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(f"Reduction summary not found: {path}")

    df = pd.read_csv(path)
    if df.empty:
        raise ValueError(f"Reduction summary is empty: {path}")

    parameter_type, parameter_col = infer_parameter_columns(df, kind)
    retained_fraction = infer_retained_fraction(df)
    n_input_col, n_reduced_col = infer_count_columns(df)

    out = pd.DataFrame(index=df.index)
    out["dataset_reduction_label"] = label
    out["reduction_kind"] = kind
    out["parameter_type"] = parameter_type
    out["parameter_value"] = as_float_series(df[parameter_col])
    out["retained_fraction"] = retained_fraction
    out["retained_percent"] = retained_fraction * 100.0
    out["removed_percent"] = 100.0 - out["retained_percent"]
    out["summary_file"] = str(path)

    if n_input_col is not None:
        out["n_input"] = pd.to_numeric(df[n_input_col], errors="coerce")
    else:
        out["n_input"] = pd.NA

    if n_reduced_col is not None:
        out["n_reduced"] = pd.to_numeric(df[n_reduced_col], errors="coerce")
    else:
        out["n_reduced"] = pd.NA

    reduced_paths = []
    for idx, row in df.iterrows():
        parameter_value = out.loc[idx, "parameter_value"]
        reduced_path = infer_reduced_dataset_path(
            row=row,
            summary_path=path,
            kind=kind,
            parameter_type=str(parameter_type),
            parameter_value=parameter_value,
        )
        reduced_paths.append(str(reduced_path) if reduced_path is not None else "")
    out["reduced_dataset"] = reduced_paths

    out = out.sort_values("parameter_value").reset_index(drop=True)
    return out


