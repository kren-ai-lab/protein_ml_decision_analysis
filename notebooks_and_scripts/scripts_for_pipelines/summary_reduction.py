def plot_general_panel(df: pd.DataFrame, output_path: Path, dpi: int) -> None:
    labels = list(df["dataset_reduction_label"].drop_duplicates())
    n_panels = len(labels)
    ncols = min(3, max(1, n_panels))
    nrows = math.ceil(n_panels / ncols)

    fig, axes = plt.subplots(
        nrows=nrows,
        ncols=ncols,
        figsize=(4.2 * ncols, 3.4 * nrows),
        squeeze=False,
    )
    axes_flat = axes.flatten()

    legend_handles = None
    legend_labels = None

    for ax, label in zip(axes_flat, labels):
        sub = df[df["dataset_reduction_label"] == label].copy()
        sub = sub.sort_values("parameter_value")
        x = list(range(len(sub)))
        xticklabels = [format_parameter(v) for v in sub["parameter_value"]]

        ax.bar(x, sub["retained_percent"], color=COLOR_RETAINED, label="Retained")
        ax.bar(
            x,
            sub["removed_percent"],
            bottom=sub["retained_percent"],
            color=COLOR_REMOVED,
            label="Removed",
        )

        parameter_type = str(sub["parameter_type"].iloc[0])
        xlabel = "Percentile" if parameter_type == "percentile" else parameter_type

        ax.set_ylim(0, 100)
        ax.set_title(label)
        ax.set_xticks(x)
        ax.set_xticklabels(xticklabels, rotation=45, ha="right")
        ax.set_xlabel(xlabel)
        ax.set_ylabel("Dataset composition (%)")
        style_axis(ax)

        if legend_handles is None:
            legend_handles, legend_labels = ax.get_legend_handles_labels()

    for ax in axes_flat[n_panels:]:
        ax.axis("off")

    if legend_handles is not None:
        fig.legend(
            legend_handles,
            legend_labels,
            loc="lower center",
            ncol=2,
            frameon=True,
            bbox_to_anchor=(0.5, -0.02),
        )

    fig.tight_layout()
    fig.savefig(output_path, dpi=dpi, bbox_inches="tight")
    plt.close(fig)


