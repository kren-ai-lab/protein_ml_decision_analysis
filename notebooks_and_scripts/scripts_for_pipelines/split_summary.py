def read_seed_summary(path: Path, split_root: Path, dataset_name: str) -> pd.DataFrame:
    meta = parse_seed_summary_path(path, split_root)
    df = pd.read_csv(path)
    if df.empty:
        return df

    if "reduction_levels" not in df.columns:
        raise ValueError(f"Missing reduction_levels column in {path}. Columns={df.columns.tolist()}")
    if "status" not in df.columns:
        raise ValueError(f"Missing status column in {path}. Columns={df.columns.tolist()}")
    if "reason" not in df.columns:
        df["reason"] = ""

    df.insert(0, "dataset_name", dataset_name)
    df.insert(1, "scenario", meta["scenario"])
    df.insert(2, "strategy", meta["strategy"])
    df.insert(3, "seed", meta["seed"])
    df["split_summary_file"] = str(path)

    parameter_types = []
    parameter_values = []
    for _, row in df.iterrows():
        ptype = infer_parameter_type(row)
        pval = infer_parameter_value(row)
        parameter_types.append(ptype)
        parameter_values.append(pval)

    df["parameter_type"] = parameter_types
    df["parameter_value"] = parameter_values
    df["threshold"] = df["reduction_levels"].where(df["reduction_levels"].astype(str) != "no_threshold", "")
    df["status"] = df["status"].fillna("unknown").astype(str)
    df["reason"] = df["reason"].fillna("").astype(str)
    df["is_kept"] = (df["status"] == "kept").astype(int)
    df["is_invalid"] = (df["status"] != "kept").astype(int)
    return df


def load_all_summaries(summary_files: list[Path], split_root: Path, dataset_name: str) -> pd.DataFrame:
    frames = []
    for path in summary_files:
        try:
            df = read_seed_summary(path, split_root, dataset_name)
        except Exception as exc:
            print(f"[WARNING] Could not read {path}: {exc}")
            continue
        if not df.empty:
            frames.append(df)

    if not frames:
        raise RuntimeError("No readable seed-level split_summary.csv files were found.")

    out = pd.concat(frames, ignore_index=True)
    out["parameter_value"] = pd.to_numeric(out["parameter_value"], errors="coerce")
    return out


def build_aggregated_summary(df: pd.DataFrame) -> pd.DataFrame:
    group_cols = [
        "dataset_name",
        "scenario",
        "strategy",
        "parameter_type",
        "threshold",
        "parameter_value",
        "reduction_levels",
    ]

    agg = (
        df.groupby(group_cols, dropna=False)
        .agg(
            n_total=("status", "size"),
            n_kept=("is_kept", "sum"),
            n_invalid=("is_invalid", "sum"),
            seeds=("seed", lambda x: ";".join(map(str, sorted(set(map(int, x))))))
        )
        .reset_index()
    )
    agg["kept_rate"] = agg["n_kept"] / agg["n_total"].replace(0, pd.NA)
    agg["invalid_rate"] = agg["n_invalid"] / agg["n_total"].replace(0, pd.NA)

    sort_param = pd.to_numeric(agg["parameter_value"], errors="coerce")
    agg["_sort_param"] = sort_param.fillna(-1)
    agg = agg.sort_values(["strategy", "parameter_type", "scenario", "_sort_param", "reduction_levels"]).drop(columns=["_sort_param"])
    return agg.reset_index(drop=True)


def build_strategy_summary(df: pd.DataFrame) -> pd.DataFrame:
    out = (
        df.groupby(["dataset_name", "strategy"], dropna=False)
        .agg(
            n_total=("status", "size"),
            n_kept=("is_kept", "sum"),
            n_invalid=("is_invalid", "sum"),
            n_scenarios=("scenario", "nunique"),
            n_seeds=("seed", "nunique"),
        )
        .reset_index()
    )
    out["kept_rate"] = out["n_kept"] / out["n_total"].replace(0, pd.NA)
    out["invalid_rate"] = out["n_invalid"] / out["n_total"].replace(0, pd.NA)
    return out.sort_values("strategy").reset_index(drop=True)


