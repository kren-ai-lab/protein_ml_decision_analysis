#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Summarize split_process outputs generated by the unified Snakemake workflow.

This version reads the public seed-level split_summary.csv files located at:

  split_process/<dataset>/<scenario>/<strategy>/seed_<seed>/split_summary.csv

It creates:
  - split_summary_all.csv
  - split_summary_aggregated.csv
  - split_summary_invalid_only.csv
  - split_summary_by_strategy.csv
  - feasibility plots separated by parameter type, so homology thresholds are
    not mixed with distance/descriptor percentiles.
"""

from __future__ import annotations

import argparse
import math
import re
from pathlib import Path

import matplotlib
matplotlib.use("Agg")

import matplotlib.pyplot as plt
from matplotlib.colors import LinearSegmentedColormap
import numpy as np
import pandas as pd


# ---------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------


def str_to_bool(value) -> bool:
    if isinstance(value, bool):
        return value
    return str(value).strip().lower() in {"true", "1", "yes", "y"}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Create global summary tables and feasibility plots for split_process."
    )
    parser.add_argument("--split-root", required=True, help="Root folder containing split outputs for one dataset.")
    parser.add_argument("--output-dir", required=True, help="Output directory for summary tables and figures.")
    parser.add_argument("--dataset-name", default="", help="Dataset name to use in output tables/figures.")
    parser.add_argument("--fig-format", default="png", choices=["png", "pdf", "svg"])
    parser.add_argument("--dpi", type=int, default=300)
    parser.add_argument(
        "--cmap",
        default="split_feasibility",
        help=(
            "Matplotlib colormap for heatmaps. Use 'split_feasibility' for a custom "
            "red-yellow-green feasibility scale."
        ),
    )
    parser.add_argument("--annotate", default="true", help="Whether to annotate heatmap cells.")
    parser.add_argument(
        "--include-no-threshold",
        default="true",
        help="Whether to include no_threshold scenarios in the no-threshold plot.",
    )
    return parser.parse_args()


# ---------------------------------------------------------------------
# Utilities
# ---------------------------------------------------------------------


def mkdir_outputs(output_dir: Path) -> tuple[Path, Path]:
    tables_dir = output_dir / "tables"
    figures_dir = output_dir / "figures"
    tables_dir.mkdir(parents=True, exist_ok=True)
    figures_dir.mkdir(parents=True, exist_ok=True)
    return tables_dir, figures_dir


def collect_seed_summary_files(split_root: Path) -> list[Path]:
    files = sorted(split_root.rglob("split_summary.csv"))
    filtered = []
    for path in files:
        # Do not read analysis outputs or hidden temporary status rows.
        if "split_analysis" in path.parts:
            continue
        if "_summary" in path.parts:
            continue
        if any(part.startswith(".") for part in path.parts):
            continue
        filtered.append(path)
    return filtered


def parse_seed_summary_path(path: Path, split_root: Path) -> dict:
    rel = path.relative_to(split_root)
    parts = rel.parts
    if len(parts) < 4:
        raise ValueError(
            f"Unexpected split_summary.csv location: {path}. Expected "
            "<scenario>/<strategy>/seed_<seed>/split_summary.csv"
        )

    scenario = parts[0]
    strategy = parts[1]
    seed_text = parts[2]
    if not seed_text.startswith("seed_"):
        raise ValueError(f"Could not infer seed from path: {path}")

    seed = int(seed_text.replace("seed_", ""))
    return {"scenario": scenario, "strategy": strategy, "seed": seed}


def threshold_to_parameter(reduction_levels: str):
    if pd.isna(reduction_levels):
        return pd.NA
    text = str(reduction_levels).strip()
    if text in {"", "no_threshold", "None", "nan", "<NA>"}:
        return pd.NA
    if text.startswith("p"):
        try:
            return float(text[1:].replace("_", "."))
        except Exception:
            return text
    if text.startswith("threshold_"):
        try:
            return float(text.replace("threshold_", ""))
        except Exception:
            return text
    if text.startswith("minseqid_"):
        try:
            return float(text.replace("minseqid_", "").replace("_", "."))
        except Exception:
            return text
    try:
        return float(text)
    except Exception:
        return text


def infer_parameter_type(row: pd.Series) -> str:
    if "percentile" in row.index and pd.notna(row.get("percentile")) and str(row.get("percentile")).strip() != "":
        return "percentile"
    if "min_seq_id" in row.index and pd.notna(row.get("min_seq_id")) and str(row.get("min_seq_id")).strip() != "":
        return "min_seq_id"

    reduction_levels = str(row.get("reduction_levels", "")).strip()
    if reduction_levels == "no_threshold":
        return "no_threshold"
    if reduction_levels.startswith("p"):
        return "percentile"
    if reduction_levels.startswith(("threshold_", "minseqid_")):
        return "min_seq_id"
    return "parameter"


def infer_parameter_value(row: pd.Series):
    parameter_type = infer_parameter_type(row)
    if parameter_type == "percentile" and "percentile" in row.index:
        return pd.to_numeric(pd.Series([row.get("percentile")]), errors="coerce").iloc[0]
    if parameter_type == "min_seq_id" and "min_seq_id" in row.index:
        return pd.to_numeric(pd.Series([row.get("min_seq_id")]), errors="coerce").iloc[0]
    return threshold_to_parameter(row.get("reduction_levels", ""))


def format_parameter(value) -> str:
    if pd.isna(value):
        return "no_threshold"
    try:
        value_f = float(value)
        if value_f.is_integer():
            return str(int(value_f))
        return f"{value_f:g}"
    except Exception:
        return str(value)


def natural_key(text: str):
    return [int(x) if x.isdigit() else x.lower() for x in re.split(r"(\d+)", str(text))]


def shorten_scenario_name(name: str) -> str:
    out = str(name)
    replacements = {
        "esm2_t6_8M_UR50D": "ESM2-8M",
        "prot_t5_xl_uniref50": "ProtT5-XL",
        "mistral_Prot_v1_134M": "Mistral-Prot",
        "ankh2_ext1": "Ankh2-ext1",
        "esmc_300m": "ESMC-300M",
        "prot_bert": "ProtBERT",
        "one_hot": "One-hot",
        "reduced_distance_by_": "reduced_distance_by_",
        "reduced_descriptor_by_": "reduced_descriptor_by_",
        "reduced_homology": "reduced_homology",
        "no_reduced": "no_reduced",
    }
    for old, new in replacements.items():
        out = out.replace(old, new)
    return out


def get_colormap(name: str):
    if name == "split_feasibility":
        return LinearSegmentedColormap.from_list(
            "split_feasibility",
            [
                (0.00, "#c43c39"),  # invalid / low kept rate
                (0.50, "#f7e6a1"),
                (1.00, "#2a9d62"),  # valid / high kept rate
            ],
        )
    return plt.get_cmap(name)


