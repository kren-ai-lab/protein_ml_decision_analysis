def style_axis(ax) -> None:
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.tick_params(axis="both", labelsize=9)


def parameter_type_label(parameter_type: str) -> str:
    if parameter_type == "percentile":
        return "Reduction percentile"
    if parameter_type == "min_seq_id":
        return "Homology min_seq_id"
    if parameter_type == "no_threshold":
        return "No reduction"
    return "Reduction parameter"


def parameter_type_slug(parameter_type: str) -> str:
    if parameter_type == "min_seq_id":
        return "homology"
    return parameter_type


def plot_heatmap(
    agg: pd.DataFrame,
    strategy: str,
    parameter_type: str,
    output_path: Path,
    dataset_name: str,
    cmap_name: str,
    annotate: bool,
    dpi: int,
) -> bool:
    sub = agg[(agg["strategy"] == strategy) & (agg["parameter_type"] == parameter_type)].copy()
    if sub.empty:
        return False

    sub["column_label"] = sub["parameter_value"].map(format_parameter)
    sub.loc[sub["reduction_levels"] == "no_threshold", "column_label"] = "no_threshold"
    sub["scenario_label"] = sub["scenario"].map(shorten_scenario_name)

    pivot = sub.pivot_table(
        index="scenario_label",
        columns="column_label",
        values="kept_rate",
        aggfunc="mean",
    )

    if pivot.empty:
        return False

    row_order = sorted(pivot.index.tolist(), key=natural_key)

    def col_sort_key(x):
        if x == "no_threshold":
            return (-1, x)
        try:
            return (float(x), x)
        except Exception:
            return (999999, x)

    col_order = sorted(pivot.columns.tolist(), key=col_sort_key)
    pivot = pivot.loc[row_order, col_order]

    values = pivot.values.astype(float)
    masked_values = np.ma.masked_invalid(values)

    n_rows, n_cols = pivot.shape
    fig_w = max(7.5, 0.75 * n_cols + 3.8)
    fig_h = max(3.4, 0.58 * n_rows + 2.4)

    cmap = get_colormap(cmap_name).copy()
    cmap.set_bad(color="#f2f2f2")

    fig, ax = plt.subplots(figsize=(fig_w, fig_h))
    im = ax.imshow(masked_values, aspect="auto", cmap=cmap, vmin=0, vmax=1)

    ax.set_xticks(np.arange(n_cols))
    ax.set_xticklabels(pivot.columns.tolist(), rotation=45, ha="right")
    ax.set_yticks(np.arange(n_rows))
    ax.set_yticklabels(pivot.index.tolist())

    ax.set_xlabel(parameter_type_label(parameter_type))
    ax.set_ylabel("Scenario")
    ax.set_title(
        f"Split feasibility\nDataset: {dataset_name} | Strategy: {strategy} | {parameter_type_label(parameter_type)}"
    )

    ax.set_xticks(np.arange(-0.5, n_cols, 1), minor=True)
    ax.set_yticks(np.arange(-0.5, n_rows, 1), minor=True)
    ax.grid(which="minor", color="white", linestyle="-", linewidth=1.1)
    ax.tick_params(which="minor", bottom=False, left=False)

    if annotate:
        for i in range(n_rows):
            for j in range(n_cols):
                val = pivot.iloc[i, j]
                if pd.isna(val):
                    continue
                val = float(val)
                text_color = "white" if val <= 0.18 or val >= 0.82 else "#1a1a1a"
                ax.text(j, i, f"{val:.2f}", ha="center", va="center", fontsize=8.5, color=text_color)

    cbar = fig.colorbar(im, ax=ax, fraction=0.035, pad=0.035)
    cbar.set_label("Kept rate")

    fig.tight_layout()
    fig.savefig(output_path, dpi=dpi, bbox_inches="tight")
    plt.close(fig)
    return True


def plot_strategy_overview(strategy_summary: pd.DataFrame, output_path: Path, dataset_name: str, dpi: int) -> None:
    if strategy_summary.empty:
        return

    df = strategy_summary.sort_values("strategy").copy()
    x = np.arange(df.shape[0])

    fig, ax = plt.subplots(figsize=(max(7.5, 1.25 * len(x)), 4.6))
    bars = ax.bar(x, df["kept_rate"], color="#5aa9a7", edgecolor="#2f6f73", linewidth=0.8)
    ax.set_ylim(0, 1.05)
    ax.set_xticks(x)
    ax.set_xticklabels(df["strategy"], rotation=35, ha="right")
    ax.set_ylabel("Kept rate")
    ax.set_title(f"Overall split feasibility\nDataset: {dataset_name}")
    ax.grid(axis="y", alpha=0.25)
    style_axis(ax)

    for bar, val in zip(bars, df["kept_rate"]):
        if pd.notna(val):
            ax.text(
                bar.get_x() + bar.get_width() / 2,
                min(float(val) + 0.03, 1.03),
                f"{float(val):.2f}",
                ha="center",
                va="bottom",
                fontsize=9,
            )

    fig.tight_layout()
    fig.savefig(output_path, dpi=dpi, bbox_inches="tight")
    plt.close(fig)


# ---------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------


def main() -> None:
    args = parse_args()

    split_root = Path(args.split_root).expanduser().resolve()
    output_dir = Path(args.output_dir).expanduser().resolve()
    dataset_name = args.dataset_name or split_root.name
    annotate = str_to_bool(args.annotate)
    include_no_threshold = str_to_bool(args.include_no_threshold)

    if not split_root.exists():
        raise FileNotFoundError(f"split_root does not exist: {split_root}")

    tables_dir, figures_dir = mkdir_outputs(output_dir)

    summary_files = collect_seed_summary_files(split_root)
    if not summary_files:
        raise RuntimeError(f"No seed-level split_summary.csv files found under: {split_root}")

    print(f"[INFO] Found {len(summary_files)} seed-level split_summary.csv files")

    all_status = load_all_summaries(summary_files, split_root=split_root, dataset_name=dataset_name)
    all_path = tables_dir / "split_summary_all.csv"
    all_status.to_csv(all_path, index=False)
    print(f"[INFO] Saved: {all_path}")

    aggregated = build_aggregated_summary(all_status)
    agg_path = tables_dir / "split_summary_aggregated.csv"
    aggregated.to_csv(agg_path, index=False)
    print(f"[INFO] Saved: {agg_path}")

    invalid = all_status[all_status["status"] != "kept"].copy()
    invalid_path = tables_dir / "split_summary_invalid_only.csv"
    invalid.to_csv(invalid_path, index=False)
    print(f"[INFO] Saved: {invalid_path}")

    strategy_summary = build_strategy_summary(all_status)
    strategy_path = tables_dir / "split_summary_by_strategy.csv"
    strategy_summary.to_csv(strategy_path, index=False)
    print(f"[INFO] Saved: {strategy_path}")

    parameter_types = sorted(
        aggregated["parameter_type"].dropna().unique().tolist(),
        key=lambda x: {"no_threshold": 0, "min_seq_id": 1, "percentile": 2}.get(x, 9),
    )

    for strategy in sorted(aggregated["strategy"].dropna().unique().tolist()):
        for parameter_type in parameter_types:
            if parameter_type == "no_threshold" and not include_no_threshold:
                continue
            slug = parameter_type_slug(parameter_type)
            fig_path = figures_dir / f"split_feasibility__{strategy}__{slug}.{args.fig_format}"
            created = plot_heatmap(
                agg=aggregated,
                strategy=strategy,
                parameter_type=parameter_type,
                output_path=fig_path,
                dataset_name=dataset_name,
                cmap_name=args.cmap,
                annotate=annotate,
                dpi=args.dpi,
            )
            if created:
                print(f"[INFO] Saved: {fig_path}")

    overview_path = figures_dir / f"split_feasibility_overall_by_strategy.{args.fig_format}"
    plot_strategy_overview(strategy_summary, overview_path, dataset_name=dataset_name, dpi=args.dpi)
    print(f"[INFO] Saved: {overview_path}")

    done = output_dir / "analysis.done"
    done.write_text("done\n", encoding="utf-8")
    print(f"[INFO] Done marker: {done}")


if __name__ == "__main__":
    main()
